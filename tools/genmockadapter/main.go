// Command genmockadapter generates the single APIClient test adapter. Keeping
// one implementation avoids compiling a promoted-method wrapper for every
// APIClient method on every command-specific mock.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const outputName = "mock_client_adapter_generated_test.go"

type method struct {
	name    string
	typeDef *ast.FuncType
	imports map[string]string
}

func main() {
	directory := flag.String("dir", "cmd", "directory containing command tests")
	check := flag.Bool("check", false, "refuse stale generated output")
	flag.Parse()
	if err := generate(*directory, *check); err != nil {
		fmt.Fprintln(os.Stderr, "genmockadapter:", err)
		os.Exit(1)
	}
}

func generate(directory string, check bool) error {
	files, err := filepath.Glob(filepath.Join(directory, "*_test.go"))
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	methods := map[string]method{}
	overrides := map[string]map[string]bool{}
	for _, name := range files {
		if filepath.Base(name) == outputName {
			continue
		}
		file, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			return err
		}
		imports := map[string]string{}
		for _, item := range file.Imports {
			path, err := strconv.Unquote(item.Path.Value)
			if err != nil {
				return err
			}
			alias := filepath.Base(path)
			if item.Name != nil {
				alias = item.Name.Name
			}
			imports[alias] = path
		}
		var embedded bool
		ast.Inspect(file, func(node ast.Node) bool {
			structure, ok := node.(*ast.StructType)
			if !ok {
				return true
			}
			for _, field := range structure.Fields.List {
				if len(field.Names) == 0 && receiverName(field.Type) == "baseMock" {
					embedded = true
				}
			}
			return true
		})
		if embedded {
			return fmt.Errorf("%s embeds baseMock: define only overrides and use adaptMockClient", name)
		}
		for _, declaration := range file.Decls {
			if group, ok := declaration.(*ast.GenDecl); ok {
				for _, specification := range group.Specs {
					if definition, ok := specification.(*ast.TypeSpec); ok && definition.Name.Name == "baseMock" {
						structure, ok := definition.Type.(*ast.StructType)
						if !ok || len(structure.Fields.List) != 0 {
							return fmt.Errorf("baseMock defaults must remain stateless; keep state on explicit mocks")
						}
					}
				}
			}
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
				continue
			}
			receiver := receiverName(fn.Recv.List[0].Type)
			if receiver == "baseMock" {
				if _, exists := methods[fn.Name.Name]; exists {
					return fmt.Errorf("duplicate baseMock method %s", fn.Name.Name)
				}
				methods[fn.Name.Name] = method{fn.Name.Name, fn.Type, imports}
			} else if receiver != "" {
				if overrides[receiver] == nil {
					overrides[receiver] = map[string]bool{}
				}
				overrides[receiver][fn.Name.Name] = true
			}
		}
	}
	if len(methods) == 0 {
		return fmt.Errorf("no baseMock methods in %s", directory)
	}
	usedImports := map[string]string{}
	for _, item := range methods {
		ast.Inspect(item.typeDef, func(node ast.Node) bool {
			if selector, ok := node.(*ast.SelectorExpr); ok {
				if name, ok := selector.X.(*ast.Ident); ok {
					if path, ok := item.imports[name.Name]; ok {
						usedImports[name.Name] = path
					}
				}
			}
			return true
		})
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./tools/genmockadapter; DO NOT EDIT.")
	fmt.Fprintln(&out, "package cmd")
	if len(usedImports) > 0 {
		fmt.Fprintln(&out, "import (")
		for _, alias := range sortedKeys(usedImports) {
			fmt.Fprintf(&out, "%s %q\n", alias, usedImports[alias])
		}
		fmt.Fprintln(&out, ")")
	}
	fmt.Fprintln(&out, "type mockClientAdapter struct { target any }")
	fmt.Fprintln(&out, "var _ APIClient = mockClientAdapter{}")
	fmt.Fprintln(&out, "var _ APIClient = baseMock{}")
	for _, name := range sortedKeys(methods) {
		item := methods[name]
		params, args := parameters(fset, item.typeDef.Params)
		results := resultTypes(fset, item.typeDef.Results)
		call := ""
		if results != "" {
			call = "return "
		}
		fmt.Fprintf(&out, "func (m mockClientAdapter) %s(%s)%s {\n", name, params, results)
		end := "; return"
		if results != "" {
			end = ""
		}
		fmt.Fprintf(&out, "if target, ok := m.target.(interface { %s(%s)%s }); ok { %starget.%s(%s)%s }\n", name, params, results, call, name, args, end)
		fmt.Fprintf(&out, "%sbaseMock{}.%s(%s)\n}\n", call, name, args)
	}
	// Every explicit override keeps its compile-time signature check. This is
	// intentionally one-method interfaces, rather than all APIClient methods
	// promoted onto each mock. Pointer checks also cover value receivers.
	for _, receiver := range sortedKeys(overrides) {
		for _, name := range sortedKeys(overrides[receiver]) {
			item, ok := methods[name]
			if !ok {
				continue
			}
			params, _ := parameters(fset, item.typeDef.Params)
			fmt.Fprintf(&out, "var _ interface { %s(%s)%s } = (*%s)(nil)\n", name, params, resultTypes(fset, item.typeDef.Results), receiver)
		}
	}
	generated, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format generated adapter: %w", err)
	}
	path := filepath.Join(directory, outputName)
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("stale %s; run go run ./tools/genmockadapter", path)
		}
		return nil
	}
	return os.WriteFile(path, generated, 0644)
}

func receiverName(expression ast.Expr) string {
	if pointer, ok := expression.(*ast.StarExpr); ok {
		expression = pointer.X
	}
	if name, ok := expression.(*ast.Ident); ok {
		return name.Name
	}
	return ""
}

func syntax(fset *token.FileSet, node ast.Node) string {
	var out bytes.Buffer
	if err := printer.Fprint(&out, fset, node); err != nil {
		panic(err)
	}
	return out.String()
}

func parameters(fset *token.FileSet, list *ast.FieldList) (string, string) {
	var declarations, arguments []string
	if list != nil {
		for _, field := range list.List {
			count := len(field.Names)
			if count == 0 {
				count = 1
			}
			for index := 0; index < count; index++ {
				name := fmt.Sprintf("a%d", len(arguments))
				declarations = append(declarations, name+" "+syntax(fset, field.Type))
				if _, variadic := field.Type.(*ast.Ellipsis); variadic {
					name += "..."
				}
				arguments = append(arguments, name)
			}
		}
	}
	return strings.Join(declarations, ", "), strings.Join(arguments, ", ")
}

func resultTypes(fset *token.FileSet, list *ast.FieldList) string {
	if list == nil || len(list.List) == 0 {
		return ""
	}
	var types []string
	for _, field := range list.List {
		count := len(field.Names)
		if count == 0 {
			count = 1
		}
		for index := 0; index < count; index++ {
			types = append(types, syntax(fset, field.Type))
		}
	}
	return " (" + strings.Join(types, ", ") + ")"
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for name := range values {
		keys = append(keys, name)
	}
	sort.Strings(keys)
	return keys
}
