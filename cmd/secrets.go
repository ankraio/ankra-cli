var secretsDeleteCmd = &cobra.Command{
	Use:   "delete <name|id>",
	Short: "Delete a secret no deployed resource references",
	Long: `Delete a secret and its stored value. This cannot be undone.

A secret that deployed resources still reference is refused, and the
resources are named: remove the sentinel from them (or remove the resources)
first. There is no --force: the platform refuses to delete a referenced
secret, because the next delivery of those resources would fail.`,
	Example: `  ankra secrets delete ci-token
  ankra secrets delete 0b6f2c1e-3c44-4b9e-9a51-2f1f6f0f9a10 --yes`,
	Args: func(_ *cobra.Command, args []string) error {
		if len(args) != 1 {
			return withExitCode(exitUsage, errors.New("delete takes exactly one secret name or id"))
		}
		return nil
	},
	RunE: func(cmd *cobra.Command, args []string) error {
		format, formatError := structuredFormatFromFlags(cmd)
		if formatError != nil {
			return formatError
		}
		yes, _ := cmd.Flags().GetBool("yes")
		ctx, cancel := context.WithTimeout(cmd.Context(), 60*time.Second)
		defer cancel()
		slot, resolveError := resolveSecretSlot(ctx, args[0])
		if resolveError != nil {
			return resolveError
		}
		if len(slot.References) > 0 {
			return secretSlotReferencedRefusal(cmd, slot, "")
		}
		if confirmError := confirmPrompt(cmd.InOrStdin(), cmd.ErrOrStderr(),
			fmt.Sprintf("Delete secret %q (id %s)? Its value cannot be recovered. [y/N]: ", slot.Label, slot.SlotID),
			yes); confirmError != nil {
			return confirmError
		}
		if _, deleteError := apiClient.DeleteSecretSlot(ctx, slot.SlotID); deleteError != nil {
			var referenced *client.SecretSlotReferencedError
			switch {
			case errors.As(deleteError, &referenced):
				// Referenced between the listing and the delete: read the
				// references again so every consumer is named, not only the
				// first one the platform's sentence carries.
				if refreshed, refreshError := resolveSecretSlot(ctx, slot.SlotID); refreshError == nil && len(refreshed.References) > 0 {
					return secretSlotReferencedRefusal(cmd, refreshed, referenced.Detail)
				}
				return fmt.Errorf("delete secret %q refused: %s", slot.Label, referenced.Detail)
			case errors.Is(deleteError, client.ErrSecretSlotNotFound):
				return withExitCode(exitNotFound, fmt.Errorf("secret %q no longer exists", slot.Label))
			}
			return fmt.Errorf("delete secret %q: %w", slot.Label, deleteError)
		}
		if format != outputDefault {
			_, renderError := renderStructured(cmd, secretSlotDeletedResult{Deleted: true, SlotID: slot.SlotID, Label: slot.Label})
			return renderError
		}
		_, _ = fmt.Fprintf(cmd.OutOrStdout(), "Deleted secret %q (id %s).\n", slot.Label, slot.SlotID)
		return nil
	},
}

// secretSlotDeletedResult is the structured answer of a delete.
type secretSlotDeletedResult struct {
	Deleted bool   `json:"deleted" yaml:"deleted"`
	SlotID  string `json:"slot_id" yaml:"slot_id"`
	Label   string `json:"label" yaml:"label"`
}

// secretSlotRefArgs takes exactly one positional argument, the secret's
// name or id. A second one is refused as a value in argv, without echoing
// it.
func secretSlotRefArgs(_ *cobra.Command, args []string) error {
	switch {
	case len(args) == 0:
		return withExitCode(exitUsage, errors.New("the secret's name or id is required"))
	case len(args) > 1:
		return errSecretValueInArgv
	}
	return nil
}

// replaceSecretSlotValue is set and rotate: resolve the secret, take the new
// value (generated, or from --from-file or stdin) and replace it in place.
func replaceSecretSlotValue(cmd *cobra.Command, reference string) error {
	format, formatError := structuredFormatFromFlags(cmd)
	if formatError != nil {
		return formatError
	}
	generate, generateError := secretSlotGenerateFromFlags(cmd)
	if generateError != nil {
		return generateError
	}
	ctx, cancel := context.WithTimeout(cmd.Context(), 60*time.Second)
	defer cancel()
	// Resolve before reading the value, so a mistyped name fails before the
	// person types or pipes a secret for nothing.
	slot, resolveError := resolveSecretSlot(ctx, reference)
	if resolveError != nil {
		return resolveError
	}
	request := client.SecretSlotReplaceRequest{Generate: generate}
	if generate == nil {
		value, valueError := readSecretSlotValue(cmd, slot.Label)
		if valueError != nil {
			return valueError
		}
		request.Value = value
	}
	replaced, replaceError := apiClient.ReplaceSecretSlot(ctx, slot.SlotID, request)
	if replaceError != nil {
		if errors.Is(replaceError, client.ErrSecretSlotNotFound) {
			return withExitCode(exitNotFound, fmt.Errorf("secret %q no longer exists", slot.Label))
		}
		return fmt.Errorf("replace the value of secret %q: %w", slot.Label, replaceError)
	}
	if format != outputDefault {
		_, renderError := renderStructured(cmd, replaced)
		return renderError
	}
	references := len(replaced.References)
	consequence := "no deployed resource references it yet"
	if references > 0 {
		consequence = fmt.Sprintf("the %d resource(s) that reference it receive the new value when Ankra next delivers them", references)
	}
	_, _ = fmt.Fprintf(cmd.OutOrStdout(),
		"Replaced the value of secret %q in place (%s). Its sentinel %s is unchanged; %s.\n",
		replaced.Label, secretSlotOrigin(replaced), replaced.Sentinel, consequence)
	return nil
}

// secretSlotGenerateFromFlags reads --generate, --length and --prefix. It
// answers nil when the command has no --generate flag or it was not set;
// --length or --prefix without --generate is a usage error.
func secretSlotGenerateFromFlags(cmd *cobra.Command) (*client.SecretSlotGenerate, error) {
	if cmd.Flags().Lookup("generate") == nil {
		return nil, nil
	}
	generate, _ := cmd.Flags().GetBool("generate")
	if !generate {
		if cmd.Flags().Changed("length") || cmd.Flags().Changed("prefix") {
			return nil, withExitCode(exitUsage, errors.New("--length and --prefix only apply with --generate"))
		}
		return nil, nil
	}
	length, _ := cmd.Flags().GetInt("length")
	prefix, _ := cmd.Flags().GetString("prefix")
	if cmd.Flags().Changed("length") && (length < 16 || length > 96) {
		return nil, withExitCode(exitUsage, errors.New("--length must be between 16 and 96"))
	}
	if len([]rune(prefix)) > 16 || strings.ContainsAny(prefix, " \t\r\n") {
		return nil, withExitCode(exitUsage, errors.New("--prefix must be at most 16 characters with no whitespace"))
	}
	if !cmd.Flags().Changed("length") {
		length = 0 // the platform's default
	}
	return &client.SecretSlotGenerate{Length: length, Prefix: prefix}, nil
}

// readSecretSlotValue reads a value from --from-file, a masked prompt on a
// terminal, or piped stdin. A file is taken byte for byte; a pipe loses
// exactly the one line ending it added. Errors name the secret, never the
// value.
func readSecretSlotValue(cmd *cobra.Command, name string) (string, error) {
	if path, _ := cmd.Flags().GetString("from-file"); path != "" {
		file, openError := os.Open(path) // #nosec G304 -- the user names the file to read
		if openError != nil {
			return "", withExitCode(exitUsage, fmt.Errorf("read the value of %q: %w", name, openError))
		}
		defer func() { _ = file.Close() }()
		data, readError := io.ReadAll(io.LimitReader(file, maxSecretValueBytes+1))
		if readError != nil {
			return "", fmt.Errorf("read the value of %q from %s: %w", name, path, readError)
		}
		return checkSecretSlotValue(name, string(data), "the file "+path)
	}
	input := cmd.InOrStdin()
	if file, isFile := input.(*os.File); isFile && readline.IsTerminal(int(file.Fd())) {
		prompt := promptui.Prompt{Label: "value of " + name, Mask: '*', Stdin: file, Stdout: os.Stderr}
		typed, promptError := prompt.Run()
		if promptError != nil {
			if isPromptCancellation(promptError) {
				return "", errCancelled
			}
			return "", fmt.Errorf("read the value of %q: %w", name, promptError)
		}
		return checkSecretSlotValue(name, strings.TrimSpace(typed), "the prompt")
	}
	data, readError := io.ReadAll(io.LimitReader(bufio.NewReader(input), maxSecretValueBytes+1))
	if readError != nil {
		return "", fmt.Errorf("read the value of %q from stdin: %w", name, readError)
	}
	value := strings.TrimSuffix(strings.TrimSuffix(string(data), "\n"), "\r")
	return checkSecretSlotValue(name, value, "stdin")
}

func checkSecretSlotValue(name, value, source string) (string, error) {
	if value == "" {
		return "", withExitCode(exitUsage, fmt.Errorf(
			"no value for %q on %s: pipe it on stdin, pass --from-file <path>, or use --generate where the command offers it",
			name, source))
	}
	if len(value) > maxSecretValueBytes {
		return "", withExitCode(exitUsage, fmt.Errorf("the value of %q from %s is over 1 MiB", name, source))
	}
	return value, nil
}

// resolveSecretSlot finds a secret by id (or its sentinel) or by its exact
// name. The listing is also what carries the references a delete checks.
func resolveSecretSlot(ctx context.Context, reference string) (*client.SecretSlot, error) {
	wanted := strings.TrimSpace(reference)
	if strings.HasPrefix(wanted, "${SECRET_SLOT:") && strings.HasSuffix(wanted, "}") {
		wanted = strings.TrimSuffix(strings.TrimPrefix(wanted, "${SECRET_SLOT:"), "}")
	}
	if wanted == "" {
		return nil, withExitCode(exitUsage, errors.New("the secret's name or id is required"))
	}
	listing, listError := apiClient.ListSecretSlots(ctx)
	if listError != nil {
		return nil, fmt.Errorf("list secrets: %w", listError)
	}
	for index := range listing.Slots {
		if strings.EqualFold(listing.Slots[index].SlotID, wanted) {
			return &listing.Slots[index], nil
		}
	}
	for index := range listing.Slots {
		if listing.Slots[index].Label == wanted {
			return &listing.Slots[index], nil
		}
	}
	return nil, withExitCode(exitNotFound, fmt.Errorf(
		"no secret named or with id %q in this organisation; 'ankra secrets list' shows them", wanted))
}

// secretSlotReferencedRefusal names every resource that still carries the
// secret's sentinel on stderr and returns the refusal.
func secretSlotReferencedRefusal(cmd *cobra.Command, slot *client.SecretSlot, platformDetail string) error {
	errOut := cmd.ErrOrStderr()
	_, _ = fmt.Fprintf(errOut, "Secret %q is referenced by %d deployed resource(s):\n", slot.Label, len(slot.References))
	for _, reference := range slot.References {
		_, _ = fmt.Fprintf(errOut, "  cluster %s: %s %s at %s\n",
			reference.ClusterName, reference.ResourceKind, reference.ResourceName, reference.DocumentPath)
	}
	message := fmt.Sprintf("secret %q is still referenced, so nothing was deleted: remove %s from the resources above first",
		slot.Label, slot.Sentinel)
	if platformDetail != "" {
		message += " (" + platformDetail + ")"
	}
	return errors.New(message)
}

// secretSlotOrigin says who supplied the current value.
func secretSlotOrigin(slot *client.SecretSlot) string {
	if slot.CreatedVia == "generated" {
		return "generated by Ankra"
	}
	return "value supplied"
}

// secretSlotExpiryPhrase describes when a secret expires, for sentences.
func secretSlotExpiryPhrase(slot *client.SecretSlot) string {
	switch {
	case slot.PinnedAt != nil:
		return "kept while referenced"
	case slot.ExpiresAt == nil:
		return "does not expire"
	default:
		return "expires " + formatSecretSlotTime(*slot.ExpiresAt) + " unless a deployed resource references it"
	}
}

func renderSecretSlots(out io.Writer, slots []client.SecretSlot, now time.Time) {
	if len(slots) == 0 {
		_, _ = fmt.Fprintln(out, "No secrets. Create one with 'ankra secrets create <name> --generate'.")
		return
	}
	writer := table.NewWriter()
	writer.SetOutputMirror(out)
	writer.SetStyle(table.StyleRounded)
	writer.AppendHeader(table.Row{"NAME", "ID", "CREATED VIA", "USED BY", "LAST USED", "EXPIRES"})
	for index := range slots {
		slot := &slots[index]
		lastUsed := "never"
		if slot.LastAccessedAt != nil {
			lastUsed = formatSecretSlotTime(*slot.LastAccessedAt)
		}
		writer.AppendRow(table.Row{slot.Label, slot.SlotID, slot.CreatedVia, secretSlotUsedBy(slot),
			lastUsed, secretSlotExpiryCell(slot, now)})
	}
	writer.Render()
}

// secretSlotUsedBy is the USED BY cell: the first reference and how many
// more there are.
func secretSlotUsedBy(slot *client.SecretSlot) string {
	if len(slot.References) == 0 {
		return "-"
	}
	first := slot.References[0]
	cell := fmt.Sprintf("%s/%s/%s", first.ClusterName, strings.ToLower(first.ResourceKind), first.ResourceName)
	if more := len(slot.References) - 1; more > 0 {
		cell += fmt.Sprintf(" (+%d more)", more)
	}
	return cell
}

func secretSlotExpiryCell(slot *client.SecretSlot, now time.Time) string {
	switch {
	case slot.PinnedAt != nil:
		return "never (in use)"
	case slot.ExpiresAt == nil:
		return "never"
	}
	if parsed, parseError := time.Parse(time.RFC3339Nano, *slot.ExpiresAt); parseError == nil && !parsed.After(now) {
		return "expired " + formatSecretSlotTime(*slot.ExpiresAt)
	}
	return formatSecretSlotTime(*slot.ExpiresAt)
}

// formatSecretSlotTime shortens a platform timestamp to minutes in UTC,
// keeping the raw text when it does not parse.
func formatSecretSlotTime(raw string) string {
	parsed, parseError := time.Parse(time.RFC3339Nano, raw)
	if parseError != nil {
		return raw
	}
	return parsed.UTC().Format("2006-01-02 15:04 UTC")
}

func init() {
	registerStructuredOutputFlags(secretsListCmd, secretsCreateCmd, secretsSetCmd, secretsRotateCmd, secretsDeleteCmd)

	secretsCreateCmd.Flags().Bool("generate", false, "Have Ankra create a random value nobody sees")
	secretsCreateCmd.Flags().Int("length", 32, "With --generate: how many random characters (16-96)")
	secretsCreateCmd.Flags().String("prefix", "", "With --generate: text in front of the random characters (at most 16, no whitespace)")
	secretsCreateCmd.Flags().String("from-file", "", "Read the value from this file, byte for byte")
	secretsCreateCmd.Flags().String("hint", "", "A note about what the secret is for (at most 240 characters)")
	secretsCreateCmd.Flags().Duration("ttl", 0, "Expire the secret after this long, e.g. 72h (a generated secret defaults to 24h, at most 168h)")
	secretsCreateCmd.MarkFlagsMutuallyExclusive("generate", "from-file")

	secretsSetCmd.Flags().String("from-file", "", "Read the new value from this file, byte for byte")

	secretsRotateCmd.Flags().Bool("generate", false, "Have Ankra create the new random value")
	secretsRotateCmd.Flags().Int("length", 32, "With --generate: how many random characters (16-96)")
	secretsRotateCmd.Flags().String("prefix", "", "With --generate: text in front of the random characters (at most 16, no whitespace)")
	secretsRotateCmd.Flags().String("from-file", "", "Read the new value from this file, byte for byte")
	secretsRotateCmd.MarkFlagsMutuallyExclusive("generate", "from-file")

	secretsDeleteCmd.Flags().Bool("yes", false, "Skip the confirmation prompt")

	secretsCmd.AddCommand(secretsListCmd, secretsCreateCmd, secretsSetCmd, secretsRotateCmd, secretsDeleteCmd)
	rootCmd.AddCommand(secretsCmd)
}
