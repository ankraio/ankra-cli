// The organisation secret commands drive the secret slot routes
// (/api/v1/org/secret-slots). A slot holds one value in Vault; manifests,
// addon values and MCP server env carry its ${SECRET_SLOT:<id>} sentinel
// instead of the value, and Ankra substitutes the value only when it seals
// the file for delivery.
//
// A value only ever travels inbound, and never through argv: it comes from
// stdin, a masked prompt, --from-file, or is generated by the platform.
// Nothing here prints, logs or echoes one, and no route hands one back.

// maxSecretValueBytes bounds a value read from stdin or a file, so a
// mistaken pipe (a whole directory listing, a binary) is refused locally
// instead of being shipped to the platform.
const maxSecretValueBytes = 1024 * 1024

// maxSecretHintLength and maxGeneratedSecretTTL are the platform's limits
// (openapi SecretSlotCreateRequest), checked here so the mistake is named
// before anything is sent.
const (
	maxSecretHintLength   = 240
	maxGeneratedSecretTTL = 7 * 24 * time.Hour
)

// errSecretValueInArgv refuses a value passed as a positional argument. The
// message never repeats the argument: it is the value.
var errSecretValueInArgv = withExitCode(exitUsage, errors.New(
	"a secret value is never taken on the command line, where shell history and the process list keep it: "+
		"pipe it on stdin, pass --from-file <path>, or use --generate"))

var secretsCmd = &cobra.Command{
	Use:     "secrets",
	Aliases: []string{"secret"},
	Short:   "Manage organisation secrets that manifests and addon values reference by sentinel",
	Long: `Manage the organisation's secrets (secret slots).

A secret holds one value in Ankra's vault. Manifests, addon values and MCP
server env reference it by its sentinel, ${SECRET_SLOT:<id>}, instead of
carrying the value, so the value never lives in Git, in a stack definition or
in a chat transcript. Ankra substitutes the value only when it seals the file
with the organisation's SOPS key for delivery: put the sentinel at a key that
the manifest's or addon's encrypted_paths declares.

Values only go in, never come out: list shows names, ids, who uses each
secret and when it was last read, never a value. A value is read from stdin,
a masked prompt or --from-file, or generated by Ankra with --generate; it is
never accepted as a command-line argument.

  ankra secrets create db-password --generate
  ankra secrets create stripe-key --from-file ./stripe.key
  printf '%s' "$TOKEN" | ankra secrets create ci-token
  ankra secrets list
  ankra secrets set stripe-key --from-file ./stripe-new.key
  ankra secrets rotate db-password --generate
  ankra secrets delete ci-token`,
}

var secretsListCmd = &cobra.Command{
	Use:   "list",
	Short: "List the organisation's secrets, never their values",
	Long: `List the organisation's secrets, newest first: name, id, whether a person
or Ankra supplied the value, the deployed resources that reference it, when
the value was last read and when the secret expires. Values are never shown.

-o json includes each secret's sentinel and every reference.`,
	Example: `  ankra secrets list
  ankra secrets list -o json`,
	Args: cobra.NoArgs,
	RunE: func(cmd *cobra.Command, _ []string) error {
		format, formatError := structuredFormatFromFlags(cmd)
		if formatError != nil {
			return formatError
		}
		ctx, cancel := context.WithTimeout(cmd.Context(), 60*time.Second)
		defer cancel()
		listing, listError := apiClient.ListSecretSlots(ctx)
		if listError != nil {
			return fmt.Errorf("list secrets: %w", listError)
		}
		if listing.Slots == nil {
			listing.Slots = []client.SecretSlot{}
		}
		if format != outputDefault {
			_, renderError := renderStructured(cmd, listing)
			return renderError
		}
		renderSecretSlots(cmd.OutOrStdout(), listing.Slots, time.Now())
		return nil
	},
}

var secretsCreateCmd = &cobra.Command{
	Use:   "create <name>",
	Short: "Create a secret and print the sentinel that stands in for its value",
	Long: `Create a secret and print its sentinel, ${SECRET_SLOT:<id>}, on stdout.
Put the sentinel where the value belongs.

The value comes from exactly one of:
  --generate          Ankra creates a random value nobody sees
  --from-file <path>  the file's bytes, exactly as stored
  stdin               piped input, without the one line ending the pipe adds;
                      on a terminal, a masked prompt (surrounding spaces are
                      dropped there, since a typed one is a typo)

It is never accepted as a command-line argument. --generate ignores stdin:
pipe a value without --generate to store it.

A generated secret expires (after one day by default, --ttl up to a week)
unless a deployed resource references its sentinel, which keeps it for as
long as it is referenced. A secret with a supplied value does not expire
unless --ttl is given.

The sentinel alone goes to stdout, so it can be captured:

  SENTINEL="$(ankra secrets create db-password --generate)"`,
	Example: `  ankra secrets create db-password --generate --length 48
  ankra secrets create stripe-key --from-file ./stripe.key --hint "Stripe live key"
  printf '%s' "$TOKEN" | ankra secrets create ci-token
  ankra secrets create ci-token -o json < token.txt`,
	Args: secretSlotRefArgs,
	RunE: func(cmd *cobra.Command, args []string) error {
		format, formatError := structuredFormatFromFlags(cmd)
		if formatError != nil {
			return formatError
		}
		name := strings.TrimSpace(args[0])
		if name == "" {
			return withExitCode(exitUsage, errors.New("the secret's name is required"))
		}
		request := client.SecretSlotCreateRequest{Label: name}
		request.Hint, _ = cmd.Flags().GetString("hint")
		if len([]rune(request.Hint)) > maxSecretHintLength {
			return withExitCode(exitUsage, fmt.Errorf("--hint is at most %d characters", maxSecretHintLength))
		}
		generate, generateError := secretSlotGenerateFromFlags(cmd)
		if generateError != nil {
			return generateError
		}
		ttl, _ := cmd.Flags().GetDuration("ttl")
		if cmd.Flags().Changed("ttl") {
			if ttl < time.Second {
				return withExitCode(exitUsage, errors.New("--ttl must be at least 1s"))
			}
			if generate != nil && ttl > maxGeneratedSecretTTL {
				return withExitCode(exitUsage, errors.New("--ttl for a generated secret is at most 168h (a week)"))
			}
			request.TTLSeconds = int(ttl / time.Second)
		}
		if generate != nil {
			request.Generate = generate
		} else {
			value, valueError := readSecretSlotValue(cmd, name)
			if valueError != nil {
				return valueError
			}
			request.Value = value
		}

		ctx, cancel := context.WithTimeout(cmd.Context(), 60*time.Second)
		defer cancel()
		slot, createError := apiClient.CreateSecretSlotWith(ctx, request)
		if createError != nil {
			return fmt.Errorf("create secret %q: %w", name, createError)
		}
		if format != outputDefault {
			_, renderError := renderStructured(cmd, slot)
			return renderError
		}
		_, _ = fmt.Fprintf(cmd.ErrOrStderr(), "Created secret %q (id %s, %s, %s). Its sentinel:\n",
			slot.Label, slot.SlotID, secretSlotOrigin(slot), secretSlotExpiryPhrase(slot))
		_, _ = fmt.Fprintln(cmd.OutOrStdout(), slot.Sentinel)
		return nil
	},
}

